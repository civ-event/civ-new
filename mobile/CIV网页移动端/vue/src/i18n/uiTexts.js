export function mergeUiTexts(baseMessages, uiTexts) {
  const locales = Object.keys(baseMessages);
  /** @type {typeof baseMessages} */
  const merged = {};
  for (const locale of locales) {
    const base = baseMessages[locale] ?? {};
    const extra = uiTexts[locale] ?? {};
    merged[locale] = {
      ...base,
      ...extra,
      nav: { ...base.nav, ...extra.nav },
      checkin: { ...base.checkin, ...extra.checkin },
      wheel: { ...base.wheel, ...extra.wheel },
      topup: { ...base.topup, ...extra.topup },
    };
  }
  return merged;
}
